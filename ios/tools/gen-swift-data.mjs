#!/usr/bin/env node
// Generates Swift data + golden test fixtures from the web app's JS sources, so the
// native port can never silently drift from src/tides.js and src/locations.js.
//
//   node ios/tools/gen-swift-data.mjs
//
// Writes:
//   Sources/.../Tides/TidePorts.generated.swift      (LINZ constants)
//   Sources/.../Locations/LocationData.generated.swift
//   Tests/.../Fixtures/tide-golden.json              (values computed by the JS predictor)
//   Tests/.../Fixtures/locations-golden.json
//
// Re-run after editing either JS file, and commit the output.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const pkg = resolve(root, "ios/Packages/WeatherTempoKit");
const out = {
  ports: `${pkg}/Sources/WeatherTempoKit/Tides/TidePorts.generated.swift`,
  locs: `${pkg}/Sources/WeatherTempoKit/Locations/LocationData.generated.swift`,
  tideGolden: `${pkg}/Tests/WeatherTempoKitTests/Fixtures/tide-golden.json`,
  locGolden: `${pkg}/Tests/WeatherTempoKitTests/Fixtures/locations-golden.json`,
};
for (const f of Object.values(out)) mkdirSync(dirname(f), { recursive: true });

// ── Load tides.js (an IIFE that attaches to `window`) ───────────────────────────
const tidesSrc = readFileSync(`${root}/src/tides.js`, "utf8");
const win = {};
new Function("window", tidesSrc)(win);
const Tides = win.Tides;

// PORTS is private to the IIFE, so lift the literal out of the source text.
const start = tidesSrc.indexOf("const PORTS = ") + "const PORTS = ".length;
const end = tidesSrc.indexOf("\n  };", start) + "\n  }".length;
const PORTS = new Function(`return (${tidesSrc.slice(start, end)})`)();

// ── Load locations.js (ES module) ───────────────────────────────────────────────
const locSrc = readFileSync(`${root}/src/locations.js`, "utf8")
  .replace(/export const/g, "const")
  .replace(/export function/g, "function");
const LOCATIONS = new Function(`${locSrc}; return LOCATIONS;`)();

// ── Swift emit helpers ──────────────────────────────────────────────────────────
const s = (v) => (v === null ? "nil" : JSON.stringify(v));
const n = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));
const camel = (id) => id.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const HEADER = "// GENERATED by ios/tools/gen-swift-data.mjs from src/*.js. DO NOT EDIT BY HAND.\n";

// ── TidePorts.generated.swift ───────────────────────────────────────────────────
// One `static let` per port (rather than one giant dictionary literal) keeps Swift's
// type checker fast.
let ports = `${HEADER}import Foundation\n\nextension TidePort {\n`;
for (const [id, p] of Object.entries(PORTS)) {
  ports += `    private static let ${camel(id)} = TidePort(id: ${s(id)}, z0: ${n(p.Z0)}, constituents: [\n`;
  for (const [name, speed, amp, phase, v0] of p.constituents) {
    ports += `        TideConstituent(name: ${s(name)}, speed: ${n(speed)}, amplitude: ${n(amp)}, phase: ${n(phase)}, v0: ${n(v0)}),\n`;
  }
  ports += `    ])\n\n`;
}
ports += `    /// All known ports, keyed by \`Location.tidePort\`.\n    public static let all: [String: TidePort] = Dictionary(\n        uniqueKeysWithValues: [\n`;
for (const id of Object.keys(PORTS)) ports += `            ${camel(id)},\n`;
ports += `        ].map { ($0.id, $0) })\n}\n`;
writeFileSync(out.ports, ports);

// ── LocationData.generated.swift ────────────────────────────────────────────────
let locs = `${HEADER}import Foundation\n\nextension Location {\n    public static let all: [Location] = [\n`;
for (const l of LOCATIONS) {
  locs += `        Location(id: ${s(l.id)}, name: ${s(l.name)}, region: ${s(l.region)}, lat: ${n(l.lat)}, lon: ${n(l.lon)}, timezone: ${s(l.timezone)}, pwsStation: ${s(l.pwsStation)}, tidePort: ${s(l.tidePort)}, tideLabel: ${s(l.tideLabel)}),\n`;
}
locs += `    ]\n}\n`;
writeFileSync(out.locs, locs);

// ── Golden fixtures (computed by the real JS predictor) ─────────────────────────
const instants = [
  "2026-01-15T03:20:00Z",
  "2026-06-21T12:00:00Z",
  "2026-11-03T00:00:00Z",
];
const heights = [];
for (const portId of Object.keys(PORTS)) {
  for (const iso of instants) {
    heights.push({ port: portId, iso, ms: Date.parse(iso), height: Tides.tideHeight(portId, Date.parse(iso)) });
  }
}
const evStart = Date.parse("2026-11-03T00:00:00Z");
const evEnd = evStart + 48 * 3_600_000;
const events = {};
for (const portId of ["lyttelton", "auckland", "nelson"]) {
  events[portId] = Tides.findTideEvents(portId, evStart, evEnd).map((e) => ({
    type: e.type, ms: e.time.getTime(), height: e.height,
  }));
}
const samples = Tides.sampleTide("lyttelton", evStart, evStart + 3 * 3_600_000, 10).map((p) => ({
  ms: p.time.getTime(), height: p.height,
}));
writeFileSync(out.tideGolden, JSON.stringify({ heights, events: { startMs: evStart, endMs: evEnd, byPort: events }, samples }, null, 1));
writeFileSync(out.locGolden, JSON.stringify(LOCATIONS, null, 1));

console.log(`ports: ${Object.keys(PORTS).length}  locations: ${LOCATIONS.length}  heights: ${heights.length}  lyttelton events: ${events.lyttelton.length}`);
// The Worker keeps its own copy of the location table (separate runtime). The native app
// sends ids from locations.js, so any drift there would produce "Unknown location" errors.
const workerSrc = readFileSync(`${root}/workers/pws-proxy.js`, "utf8");
const wStart = workerSrc.indexOf("const LOCATIONS = ") + "const LOCATIONS = ".length;
const WORKER = new Function(`return (${workerSrc.slice(wStart, workerSrc.indexOf("\n};", wStart) + 2)})`)();
const drift = [];
for (const l of LOCATIONS) {
  const w = WORKER[l.id];
  if (!w) drift.push(`${l.id}: missing in worker`);
  else if (Math.abs(w.lat - l.lat) > 1e-9 || Math.abs(w.lon - l.lon) > 1e-9) drift.push(`${l.id}: coordinates differ`);
  else if ((w.pwsStation ?? null) !== (l.pwsStation ?? null)) drift.push(`${l.id}: pwsStation differs`);
}
for (const id of Object.keys(WORKER)) if (!LOCATIONS.some((l) => l.id === id)) drift.push(`${id}: only in worker`);
if (drift.length) { console.error("Worker/web location drift:\n  " + drift.join("\n  ")); process.exit(1); }

const badPorts = LOCATIONS.filter((l) => l.tidePort && !PORTS[l.tidePort]).map((l) => l.id);
if (badPorts.length) { console.error("Locations referencing unknown tide ports:", badPorts); process.exit(1); }
